md_open <- function(script, title) {
  MD <<- file.path(AUD, paste0(sub("\\.R$", "", basename(script)), ".md"))
  cat(sprintf("# %s\n\nGenerated by `final_verification/R/%s` on %s.\n\n", title, basename(script), format(Sys.time(), "%Y-%m-%d %H:%M")), file = MD)
  cat(sprintf("\n## %s — %s\n", basename(script), format(Sys.time(), "%Y-%m-%d %H:%M")), file = LOG_FILE, append = TRUE)
}
