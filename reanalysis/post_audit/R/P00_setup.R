md_open <- function(script, title) {   # same as the audit version, but writes to post_audit/output
  MD <<- file.path(AUD, paste0(sub("\\.R$", "", basename(script)), ".md"))
  cat(sprintf("# %s\n\nGenerated by `post_audit/R/%s` on %s.\n\n", title, basename(script), format(Sys.time(), "%Y-%m-%d %H:%M")), file = MD)
  cat(sprintf("\n## %s — `post_audit/R/%s` (%s)\n", title, basename(script), format(Sys.time(), "%Y-%m-%d %H:%M")), file = LOG_FILE, append = TRUE)
}
