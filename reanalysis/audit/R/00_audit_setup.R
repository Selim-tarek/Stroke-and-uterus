# every table is written as CSV (git-ignored) and appended as Markdown to one file per script, so results are readable in the repo
MD <- NULL
md_open <- function(script, title) {
  MD <<- file.path(AUD, paste0(sub("\\.R$", "", basename(script)), ".md"))
  cat(sprintf("# %s\n\nGenerated by `audit/R/%s` on %s. Development sample definition identical to `R/16_calculator_model.R:6`.\n\n",
              title, basename(script), format(Sys.time(), "%Y-%m-%d %H:%M")), file = MD)
  cat(sprintf("\n## %s — `audit/R/%s` (%s)\n", title, basename(script), format(Sys.time(), "%Y-%m-%d %H:%M")), file = LOG_FILE, append = TRUE)
}
md_note <- function(...) cat(paste0(..., "\n\n"), file = MD, append = TRUE)
aud_tab <- function(dt, name, caption = "") {
  dt <- as.data.table(dt)
  fwrite(dt, file.path(AUD, "tables", paste0(name, ".csv")), bom = TRUE)
  x <- copy(dt); for (j in names(x)) set(x, j = j, value = { v <- x[[j]]; if (is.numeric(v)) format(v, big.mark = ",", scientific = FALSE, trim = TRUE, drop0trailing = TRUE) else as.character(v) })
  body <- c(paste0("| ", paste(names(x), collapse = " | "), " |"), paste0("|", strrep("---|", ncol(x))),
            apply(x, 1, function(r) paste0("| ", paste(gsub("\\|", "/", ifelse(is.na(r), "", r)), collapse = " | "), " |")))
  cat(sprintf("### %s\n\n%s%s\n\n", name, if (nzchar(caption)) paste0(caption, "\n\n") else "", paste(body, collapse = "\n")), file = MD, append = TRUE)
  cat(sprintf("- table `%s` (%d rows)\n", name, nrow(dt)), file = LOG_FILE, append = TRUE)
  invisible(dt)
}
aud_log <- function(...) { cat(paste0("- ", ..., "\n"), file = LOG_FILE, append = TRUE); message(...) }

