fml_of <- function(pred, lhs = "Surv(t, y)") as.formula(paste(lhs, "~", paste(pred, collapse = " + ")))
risk_spec <- function(dd, spec = SPEC9, h_s0 = spec$s0, shrink = spec$shrink) {
  P <- names(spec$coef); b <- unlist(spec$coef[P]); mu <- unlist(spec$means[P])
  1 - h_s0^exp(shrink * drop(sweep(as.matrix(dd[, ..P]), 2, mu) %*% b))
}
s0_at <- function(f, h) { bh <- basehaz(f, centered = TRUE); exp(-approx(bh$time, bh$hazard, xout = h, rule = 2)$y) }
lp_c  <- function(f, dd, pred) drop(sweep(as.matrix(dd[, ..pred]), 2, f$means[pred]) %*% coef(f)[pred])
harrell <- function(lp, dd, h = Inf) { yy <- dd$y * (dd$t <= h); tt <- pmin(dd$t, h)
  concordance(Surv(tt, yy) ~ lp, reverse = TRUE) }
km_risk <- function(dd, h) { s <- summary(survfit(Surv(t, y) ~ 1, data = dd), times = h, extend = TRUE)
  c(est = 1 - s$surv, lo = 1 - s$upper, hi = 1 - s$lower) }
pct <- function(x, d = 1) formatC(100 * x, format = "f", digits = d)
smd <- function(a, b) { ma <- mean(a, na.rm = TRUE); mb <- mean(b, na.rm = TRUE)
  (ma - mb) / sqrt((var(a, na.rm = TRUE) + var(b, na.rm = TRUE)) / 2) }
pois_ci <- function(k, py, per = 1000) { ci <- if (k == 0) c(0, qchisq(.975, 2) / 2) else c(qchisq(.025, 2 * k) / 2, qchisq(.975, 2 * k + 2) / 2)
  sprintf("%.2f (%.2f–%.2f)", per * k / py, per * ci[1] / py, per * ci[2] / py) }
